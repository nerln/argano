@pytest.fixture(scope="session")
def hevc_aac(samples: Path) -> Path | None:
    """H.265, which is what a recent phone records by default."""
    if not FFMPEG:
        return None
    codecs = subprocess.run([FFMPEG, "-hide_banner", "-encoders"],
                            capture_output=True, text=True).stdout
    encoder = None
    for candidate in ("libx265", "hevc_videotoolbox"):
        if candidate in codecs:
            encoder = candidate
            break
    if encoder is None:
        return None
    try:
        return _encode(
            samples / "hevc-aac.mp4",
            [
                "-f", "lavfi", "-i", "testsrc2=size=320x240:rate=25:duration=5",
                "-f", "lavfi", "-i", "sine=frequency=520:sample_rate=44100:duration=5",
                "-c:v", encoder, "-g", "25", "-pix_fmt", "yuv420p",
                "-c:a", "aac", "-b:a", "96k", "-ac", "1",
                "-tag:v", "hvc1", "-f", "mp4",
            ],
        )
    except subprocess.CalledProcessError:
        return None
