"""Fixtures made on the spot, so the tests carry no video with them.

Every sample here is generated by ffmpeg at the start of a run. That keeps the
repository small, and it means the tests are about the format rather than about
one person's recording: change the codec, the frame rate or the audio and the
same assertions have to hold.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

FFMPEG = shutil.which("ffmpeg")
FFPROBE = shutil.which("ffprobe")

needs_ffmpeg = pytest.mark.skipif(
    not FFMPEG or not FFPROBE, reason="these tests build their samples with ffmpeg"
)


def _encode(destination: Path, args: list[str]) -> Path:
    if destination.exists():
        return destination
    destination.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [FFMPEG, "-hide_banner", "-loglevel", "error", "-y", *args, str(destination)],
        check=True,
    )
    return destination


def probe(path: Path) -> dict:
    """Frame counts, geometry and duration, straight from ffprobe."""
    out = subprocess.run(
        [FFPROBE, "-v", "error", "-count_frames" if False else "-show_entries",
         "format=duration:stream=codec_type,codec_name,width,height,nb_frames,duration",
         "-of", "json", str(path)],
        capture_output=True, text=True, check=True,
    ).stdout
    import json

    data = json.loads(out)
    result = {"duration": float(data["format"].get("duration", 0) or 0)}
    for stream in data.get("streams", []):
        kind = stream["codec_type"]
        result[kind] = {
            "codec": stream.get("codec_name"),
            "frames": int(stream.get("nb_frames", 0) or 0),
            "width": int(stream.get("width", 0) or 0),
            "height": int(stream.get("height", 0) or 0),
            "duration": float(stream.get("duration", 0) or 0),
        }
    return result


def decode_errors(path: Path) -> list[str]:
    """What a strict decoder complains about when it reads the whole file."""
    result = subprocess.run(
        [FFMPEG, "-v", "error", "-i", str(path), "-map", "0", "-f", "null", "-"],
        capture_output=True, text=True,
    )
    return [
        line for line in result.stderr.splitlines()
        if line.strip() and "non monotonically increasing dts" not in line
    ]


@pytest.fixture(scope="session")
def samples(tmp_path_factory) -> Path:
    return tmp_path_factory.mktemp("samples")


