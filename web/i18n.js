/* A sentence from ./lib in the page's language, or null when this file does
 * not know it. English is returned as it came. */
export function fromLib(lang, text) {
  const value = String(text ?? '');
  if (lang === 'en' || !value) return value;
  for (const [pattern, langs] of LIB) {
    const match = value.match(pattern);
    if (!match || !(lang in langs)) continue;
    const said = langs[lang];
    return typeof said === 'function' ? said(...match.slice(1)) : said;
  }
  return null;
}
